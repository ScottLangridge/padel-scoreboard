#!/usr/bin/env python3
"""Converts a design/frames/*.json clip into a C header of fixed frames.

    tools/frames_to_header.py design/frames/splash.json main/splash_frames.h SPLASH [cutoff_s]

Frames are {ms, hex} with hex = 128 hex chars = 512 bits, row-major from
(0,0), MSB first, 1 = on; consecutive identical frames are already merged.
With a cutoff, only the frames that start before cutoff seconds are kept and
the last one is trimmed to end exactly at the cutoff.
"""

import json
import sys


def main(src, out, name, cutoff=None):
    clip = json.load(open(src))
    frames = clip["frames"] if isinstance(clip, dict) else clip
    # Work in source frames (30 fps) rather than the rounded ms values, whose
    # sum drifts from the true time; the output ms are re-derived without drift.
    fps = clip.get("fps_source", 30) if isinstance(clip, dict) else 30
    limit = round(cutoff * fps) if cutoff is not None else None
    kept = []
    count = 0
    for frame in frames:
        ticks = round(frame["ms"] * fps / 1000)
        if limit is not None:
            ticks = min(ticks, limit - count)
        if ticks <= 0:
            break
        start, end = count, count + ticks
        kept.append((round(end * 1000 / fps) - round(start * 1000 / fps), frame["hex"]))
        count = end
    total_ms = round(count * 1000 / fps)
    with open(out, "w") as header_file:
        header_file.write(f"// Generated by tools/frames_to_header.py from {src.split('/')[-1]}. Do not edit.\n")
        header_file.write(f"// {len(kept)} frames, {total_ms} ms.\n\n#pragma once\n\n#include \"canvas.h\"\n\n")
        header_file.write(f"static const FixedFrame {name}[] = {{\n")
        for ms, frame_hex in kept:
            rows = [int(frame_hex[y * 8:(y + 1) * 8], 16) for y in range(16)]
            header_file.write(f"    {{{ms}, {{" + ", ".join(f"0x{row:08x}" for row in rows) + "}},\n")
        header_file.write("};\n")
    print(f"{out}: {len(kept)} frames, {total_ms} ms")


if __name__ == "__main__":
    if len(sys.argv) not in (4, 5):
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3], float(sys.argv[4]) if len(sys.argv) == 5 else None)
