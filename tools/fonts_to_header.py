#!/usr/bin/env python3
"""Converts design/fonts.json into main/fonts.h.

    tools/fonts_to_header.py design/fonts.json main/fonts.h

Each glyph becomes one byte per row with the leftmost column in the most
significant used bit (bit width-1). Glyphs are indexed by ASCII code 32..127;
codes without a glyph point at a blank entry.
"""

import json
import sys

FONTS = [  # json key, C name, width, height
    ("5x7", "FONT_5X7", 5, 7),
    ("3x5", "FONT_3X5", 3, 5),
    ("4x7_condensed", "FONT_4X7", 4, 7),
]


def main(src, out):
    fonts = json.load(open(src))
    lines = [
        f"// Generated by tools/fonts_to_header.py from {src.split('/')[-1]}. Do not edit.",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "struct Font {",
        "    uint8_t width, height, advance;",
        "    const uint8_t (*glyphs)[7]; // [96] for ASCII 32..127, row bytes, leftmost column in bit (width-1)",
        "};",
        "",
    ]
    for key, cname, w, h in FONTS:
        f = fonts[key]
        glyphs = f["glyphs"]
        lines.append(f"static const uint8_t {cname}_GLYPHS[96][7] = {{")
        for code in range(32, 128):
            ch = chr(code)
            rows = glyphs.get(ch)
            if rows is None:
                lines.append("    {0},")
                continue
            assert len(rows) == h and all(len(r) == w for r in rows), (key, ch)
            vals = []
            for r in rows:
                v = 0
                for i, c in enumerate(r):
                    if c == "#":
                        v |= 1 << (w - 1 - i)
                vals.append(f"0x{v:02x}")
            lines.append(f"    {{{', '.join(vals)}}}, // '{ch}'")
        lines.append("};")
        lines.append(f"static const Font {cname} = {{{w}, {h}, {f['advance']}, {cname}_GLYPHS}};")
        lines.append("")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"{out}: {len(FONTS)} fonts")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
