#!/usr/bin/env python3
"""Turns the project's sdkconfig into the sdkconfig.h the emulator includes.

    emulator/gen_sdkconfig.py sdkconfig emulator/build/sdkconfig.h

Does what ESP-IDF's build does for the settings in use: CONFIG_X=y becomes
1, numbers and quoted strings are copied, unset options are left out. The
emulator so runs with the same menuconfig settings as the firmware.
"""

import sys


def main(src, out):
    lines = [f"// Generated by emulator/gen_sdkconfig.py from {src}. Do not edit.", "#pragma once", ""]
    for line in open(src):
        line = line.strip()
        if not line.startswith("CONFIG_") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        lines.append(f"#define {name} {'1' if value == 'y' else value}")
    with open(out, "w") as header_file:
        header_file.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
